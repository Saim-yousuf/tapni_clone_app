String normalizeCurrencyCode(String? value) {
  final code = (value ?? '').trim().toUpperCase();
  if (code.length == 3) return code;
  return '';
}

String currencyFromCountryName(String? country) {
  final key = (country ?? '').trim().toLowerCase();
  if (key.isEmpty) return kDefaultCurrency;
  if (key.length == 2) {
    return kIsoToCurrency[key] ?? kDefaultCurrency;
  }
  return kCountryNameToCurrency[key] ?? kDefaultCurrency;
}

