String resolveCurrency({String? currency, String? country}) {
  final explicit = normalizeCurrencyCode(currency);
  if (explicit.isNotEmpty) return explicit;
  if (country != null && country.trim().isNotEmpty) {
    return currencyFromCountryName(country);
  }
  return kDefaultCurrency;
}

String currencySymbol(String? currency) {
  final code = resolveCurrency(currency: currency);
  return kCurrencySymbols[code] ?? code;
}

/// Formats [amount] for display in [currency] (business-local, no FX).
String formatMoney(
  num amount, {
  String? currency,
  String? freeLabel,
  bool compact = true,
}) {
  final value = amount.toDouble();
  if (value <= 0 && freeLabel != null) return freeLabel;
  final code = resolveCurrency(currency: currency);
  final symbol = currencySymbol(code);

  if (compact && value == value.roundToDouble()) {
    final whole = NumberFormat('#,##0', 'en').format(value.round());
    return '$symbol $whole';
  }

  try {
    return NumberFormat.currency(
      name: code,
      symbol: '$symbol ',
      decimalDigits: compact ? 0 : 2,
    ).format(value);
  } catch (_) {
    final formatted = NumberFormat('#,##0.##', 'en').format(value);
    return '$symbol $formatted';
  }
}

String priceFieldLabel(String? currency) {
  final code = resolveCurrency(currency: currency);
  return 'Price ($code)';
}
