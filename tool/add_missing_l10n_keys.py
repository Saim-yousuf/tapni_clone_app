def merge_arb(path: Path, translations: dict[str, str], is_template: bool) -> int:
    data = json.loads(path.read_text(encoding="utf-8"))
    added = 0
    for key, value in translations.items():
        if key not in data:
            data[key] = value
            added += 1
        elif is_template:
            # keep existing template text; only fill missing
            pass
        else:
            # for AR, fill if missing only
            pass
        if is_template and key in PLACEHOLDERS:
            meta_key = f"@{key}"
            if meta_key not in data:
                data[meta_key] = _ph_meta(key)
        if not is_template and key in PLACEHOLDERS:
            meta_key = f"@{key}"
            if meta_key not in data:
                data[meta_key] = _ph_meta(key)
    # Ensure AR gets all new values even if key somehow existed empty
